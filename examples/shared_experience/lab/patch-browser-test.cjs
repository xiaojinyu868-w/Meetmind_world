const {chromium}=require(process.env.PLAYWRIGHT_MODULE||"playwright");
const fs=require("node:fs"), path=require("node:path"), assert=require("node:assert/strict");
(async()=>{
  const mode=process.env.PATCH_RESPONSE_MODE;
  if(!["live-patch","captured-patch","fixture-patch"].includes(mode)) throw new Error("Use an isolated seeded QA server; set PATCH_RESPONSE_MODE explicitly");
  const out=process.env.LAB_EVIDENCE_DIR||path.join(require("node:os").tmpdir(),"meetmind-patch-evidence");
  fs.mkdirSync(out,{recursive:true});
  const browser=await chromium.launch({...process.env.CHROMIUM_EXECUTABLE?{executablePath:process.env.CHROMIUM_EXECUTABLE}:{},headless:true});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1060}});
    const errors=[];
    page.on("pageerror",e=>errors.push(e.message));
    await page.goto(process.env.LAB_URL||"http://127.0.0.1:4192/");
    await page.locator("#sequence").filter({hasText:"事件 #8"}).waitFor();
    await page.getByRole("button",{name:"生成视觉提案",exact:true}).click();
    await page.getByRole("button",{name:"应用这个提案",exact:true}).click();
    await page.getByRole("button",{name:"生成局部修改提案",exact:true}).waitFor();
    await page.waitForFunction(()=>JSON.parse(document.querySelector("#diagnostic").textContent).objects.find(o=>o.id==="artifact-1").recipeParts>0);
    const state=async()=>JSON.parse(await page.locator("#json").textContent());
    const diag=async()=>JSON.parse(await page.locator("#diagnostic").textContent());
    const before=await state(),beforeDiag=await diag();
    await page.getByLabel("生成要求",{exact:true}).fill("保留所有现有部件原样，不修改不删除。在河流底板旁边加一盏有支撑的暖黄色小灯，最多3个部件。灯象征以后继续一起创作的愿望，并不代表现实已经发生。");
    const responsePromise=page.waitForResponse(r=>r.url().endsWith("/lab-api/proposals"),{timeout:110000});
    await page.getByRole("button",{name:"生成局部修改提案",exact:true}).click();
    const response=await responsePromise,proposal=await response.json();
    fs.writeFileSync(path.join(out,"proposal.json"),JSON.stringify(proposal,null,2));
    assert.ok(response.ok(),JSON.stringify(proposal));
    assert.equal(proposal.mode,"patch");
    assert.deepEqual(await state(),before);
    assert.ok(proposal.changes.added.length>0 && proposal.changes.added.length<=3);
    assert.equal(proposal.changes.updated.length,0);
    assert.equal(proposal.changes.removed.length,0);
    await page.locator(".recipe-diff").waitFor();
    await page.getByRole("button",{name:"应用这个提案",exact:true}).click();
    await page.locator("#sequence").filter({hasText:"事件 #10"}).waitFor();
    await page.waitForFunction(expected=>JSON.parse(document.querySelector("#diagnostic").textContent).objects.find(o=>o.id==="artifact-1").recipeParts===expected,
      proposal.recipe.parts.length);
    const after=await state(),afterDiag=await diag();
    const entity=after.entities.find(e=>e.id==="artifact-1"),old=before.entities.find(e=>e.id==="artifact-1");
    assert.equal(entity.provenance.at(-1).type,"visual.recipe.patched");
    for(const part of old.appearance.parts) assert.deepEqual(entity.appearance.parts.find(p=>p.id===part.id),part);
    const oldObject=beforeDiag.objects.find(o=>o.id==="artifact-1"),newObject=afterDiag.objects.find(o=>o.id==="artifact-1");
    assert.equal(newObject.uuid,oldObject.uuid);
    assert.deepEqual(newObject.position,oldObject.position);
    assert.equal(newObject.recipeError,null);
    for(const part of oldObject.parts) assert.deepEqual(newObject.parts.find(p=>p.id===part.id),part);
    assert.deepEqual(after.relationships,before.relationships);
    assert.deepEqual(after.entities.find(e=>e.kind==="action"),before.entities.find(e=>e.kind==="action"));
    await page.locator(".viewport").scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(out,"desktop-patched.png"),fullPage:true});
    await page.locator("canvas").screenshot({path:path.join(out,"patched-canvas.png")});
    await page.getByLabel("呈现模式",{exact:true}).selectOption("2d");
    await page.locator(".baseline").waitFor({state:"visible"});
    assert.deepEqual(await state(),after);
    await page.locator("#detail").getByText(entity.appearance.rationale,{exact:true}).waitFor();
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(out,"mobile-patched.png"),fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.getByRole("button",{name:"恢复默认外观",exact:true}).click();
    await page.getByRole("button",{name:"生成视觉提案",exact:true}).waitFor();
    assert.equal((await state()).entities.find(e=>e.id==="artifact-1").appearance,undefined);
    assert.deepEqual(errors,[]);
    fs.writeFileSync(path.join(out,"report.json"),JSON.stringify({responseMode:mode,initialRecipe:mode === "fixture-patch" ? "authored test fixture" : "captured real output from prior milestone",model:proposal.model,latency_ms:proposal.latency_ms,changes:proposal.changes,beforeDiag,afterDiag,errors,passed:["review before mutation","requested additions only","old part data preserved","old mesh/geometry/material UUIDs preserved","world identity and relationships preserved","2D parity","mobile layout","restore"]},null,2));
    console.log(JSON.stringify({out,mode,latency_ms:proposal.latency_ms,changes:proposal.changes}));
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
