const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const fs = require("node:fs");
const path = require("node:path");
const assert = require("node:assert/strict");
(async () => {
  const live = process.env.RUN_LIVE_RECIPE === "1";
  if (!live && process.env.RECIPE_TEST_MODE !== "captured") throw new Error("Set RUN_LIVE_RECIPE=1 for a model call, or RECIPE_TEST_MODE=captured with an isolated fixture server");
  const out = process.env.LAB_EVIDENCE_DIR || path.join(require("node:os").tmpdir(), "meetmind-recipe-evidence");
  fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ ...(process.env.CHROMIUM_EXECUTABLE ? {executablePath:process.env.CHROMIUM_EXECUTABLE} : {}), headless: true });
  try {
    const page = await browser.newPage({ viewport:{width:1440,height:1060},deviceScaleFactor:1 });
    const errors = [];
    page.on("pageerror", e => errors.push(e.message));
    page.on("console", m => { if(m.type()==="error") errors.push(m.text()); });
    await page.goto(process.env.LAB_URL || "http://127.0.0.1:4191/");
    await page.locator("#sequence").filter({hasText:"事件 #8"}).waitFor();
    await page.waitForFunction(()=>JSON.parse(document.querySelector("#diagnostic").textContent).drawCalls>10);
    const state = async()=>JSON.parse(await page.locator("#json").textContent());
    const diag = async()=>JSON.parse(await page.locator("#diagnostic").textContent());
    const before = await state(), beforeDiag = await diag();
    await page.getByLabel("生成要求",{exact:true}).fill("把共同完成的纸桥设计成精致纸艺纪念物。主体是一座暖白色有支撑的拱桥，深青色河流底板，两侧少量折纸植物，造型整体连贯，克制用色。桥表示共同创作；河流与植物是视觉象征，不增加真实经历。");
    const reply = page.waitForResponse(r=>r.url().endsWith("/lab-api/proposals"),{timeout:110000});
    await page.getByRole("button",{name:"生成视觉提案",exact:true}).click();
    const response = await reply;
    const proposal = await response.json();
    if(!response.ok()) {
      fs.writeFileSync(path.join(out,"failure.json"),JSON.stringify({status:response.status(),error:proposal.error},null,2));
      throw new Error(JSON.stringify(proposal));
    }
    fs.writeFileSync(path.join(out,"proposal.json"),JSON.stringify(proposal,null,2));
    assert.deepEqual(await state(),before,"Proposal changed world before apply");
    await page.getByRole("button",{name:"应用这个提案",exact:true}).click();
    await page.getByRole("button",{name:"恢复默认外观",exact:true}).waitFor();
    await page.waitForFunction(()=>JSON.parse(document.querySelector("#diagnostic").textContent).objects.find(o=>o.id==="artifact-1").recipeParts>0);
    const applied = await state(), appliedDiag = await diag();
    const old = beforeDiag.objects.find(o=>o.id==="artifact-1");
    const current = appliedDiag.objects.find(o=>o.id==="artifact-1");
    assert.equal(current.uuid,old.uuid);
    assert.deepEqual(current.position,old.position);
    assert.equal(current.recipeError,null);
    assert.equal(current.recipeParts,proposal.recipe.parts.length);
    const entity=applied.entities.find(i=>i.id==="artifact-1"), previous=before.entities.find(i=>i.id==="artifact-1");
    assert.equal(entity.title,previous.title);
    assert.equal(entity.source_event,previous.source_event);
    assert.deepEqual(applied.relationships,before.relationships);
    assert.deepEqual(applied.entities.find(i=>i.kind==="action"),before.entities.find(i=>i.kind==="action"));
    await page.locator(".viewport").scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(out,"desktop-generated.png"),fullPage:true});
    await page.locator("canvas").screenshot({path:path.join(out,"generated-canvas.png")});
    await page.getByLabel("呈现模式",{exact:true}).selectOption("2d");
    await page.locator(".baseline").waitFor({state:"visible"});
    assert.deepEqual(await state(),applied);
    await page.locator("#detail").getByText(proposal.recipe.rationale,{exact:true}).waitFor();
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(out,"mobile-recipe.png"),fullPage:true});
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
    assert.equal(overflow,false);
    await page.getByRole("button",{name:"恢复默认外观",exact:true}).click();
    await page.getByRole("button",{name:"恢复默认外观",exact:true}).waitFor({state:"detached"});
    const restored=await state();
    assert.equal(restored.entities.find(i=>i.id==="artifact-1").appearance,undefined);
    await page.getByLabel("呈现模式",{exact:true}).selectOption("3d");
    await page.waitForFunction(()=>JSON.parse(document.querySelector("#diagnostic").textContent).objects.find(o=>o.id==="artifact-1").recipeParts===0);
    assert.equal((await diag()).objects.find(o=>o.id==="artifact-1").uuid,old.uuid);
    assert.deepEqual(errors,[]);
    fs.writeFileSync(path.join(out,"report.json"),JSON.stringify({responseMode:live ? "live" : "captured-replay",model:proposal.model,latency_ms:proposal.latency_ms,partCount:proposal.recipe.parts.length,errors,overflow,beforeDiag,appliedDiag,passed:[live ? "live provider response" : "captured provider response replay","proposal before mutation","semantic parts rendered","root identity and position retained","relationships and real outcomes unchanged","2D state and meaning parity","mobile no horizontal overflow","restore default"]},null,2));
    console.log(JSON.stringify({out,model:proposal.model,latency_ms:proposal.latency_ms,parts:proposal.recipe.parts.length}));
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exit(1);});
