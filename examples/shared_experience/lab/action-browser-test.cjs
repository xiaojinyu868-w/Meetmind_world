const {chromium}=require(process.env.PLAYWRIGHT_MODULE||"playwright");
const fs=require("node:fs"), path=require("node:path"), assert=require("node:assert/strict");
(async()=>{
  const out=process.env.LAB_EVIDENCE_DIR||path.join(require("node:os").tmpdir(),"meetmind-action-evidence");
  fs.mkdirSync(out,{recursive:true});
  const browser=await chromium.launch({...process.env.CHROMIUM_EXECUTABLE?{executablePath:process.env.CHROMIUM_EXECUTABLE}:{},headless:true});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1060},timezoneId:"Asia/Shanghai",acceptDownloads:true});
    const errors=[];
    page.on("pageerror",e=>errors.push(e.message));
    await page.goto(process.env.LAB_URL||"http://127.0.0.1:4191/");
    await page.locator("#sequence").filter({hasText:"事件 #8"}).waitFor();
    const state=async()=>JSON.parse(await page.locator("#json").textContent());
    await page.locator(".import-panel summary").click();
    await page.getByRole("button",{name:"载入合成签到示例",exact:true}).click();
    await page.getByLabel("签到可见范围",{exact:true}).selectOption("shared");
    await page.locator("#checkin-confirm").check();
    await page.getByRole("button",{name:"确认并导入签到",exact:true}).click();
    await page.locator("#sequence").filter({hasText:"事件 #9"}).waitFor();
    const imported=(await state()).entities.find(e=>e.source?.record_id==="synthetic-visit-001");
    assert.ok(imported);
    await page.locator('#entities [data-entity-id="'+imported.id+'"]').click();
    await page.locator(".action-composer summary").click();
    await page.getByLabel("下一步具体做什么",{exact:true}).fill("周二一起整理三张旅行照片");
    await page.getByLabel("计划时间（本机时区）",{exact:true}).fill("2026-09-15T19:30");
    await page.getByLabel("预计时长（分钟）",{exact:true}).fill("45");
    await page.getByLabel("行动地点",{exact:true}).fill("楼下咖啡厅");
    await page.getByLabel("怎样算完成",{exact:true}).fill("各自选出三张照片，说明最想保留的一个细节");
    await page.setViewportSize({width:390,height:844});
    await page.getByLabel("行动参与者：阿博",{exact:true}).check();
    await page.screenshot({path:path.join(out,"mobile-composer.png"),fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    const requestPromise=page.waitForRequest(r=>r.url().endsWith("/lab-api/commands")&&r.postDataJSON()?.command==="action.proposed");
    await page.getByRole("button",{name:"提出这次行动",exact:true}).click();
    const createRequest=(await requestPromise).postDataJSON();
    await page.getByRole("heading",{name:"周二一起整理三张旅行照片",exact:true}).waitFor();
    await page.setViewportSize({width:1440,height:1060});
    const created=await state(),action=created.entities.find(e=>e.title==="周二一起整理三张旅行照片");
    assert.equal(action.plan.scheduled_at,"2026-09-15T11:30:00Z");
    assert.deepEqual(action.decisions,{});
    assert.deepEqual(action.outcomes,{});
    assert.deepEqual(action.basis_event_ids,[imported.source_event]);
    assert.equal(created.basis.through_sequence,10);
    const retry=await page.request.post(new URL("/lab-api/commands",page.url()).href,{data:createRequest});
    assert.ok(retry.ok());
    assert.deepEqual(await retry.json(),created);
    const calendarUrl="/lab-api/calendar?"+new URLSearchParams({session_id:createRequest.session_id,viewer:"alice",action_id:action.id});
    assert.equal((await page.request.get(new URL(calendarUrl,page.url()).href)).status(),400);
    assert.equal(await page.getByRole("link",{name:"下载我的日历文件",exact:true}).count(),0);
    await page.getByRole("button",{name:"我愿意参加",exact:true}).click();
    await page.getByRole("link",{name:"下载我的日历文件",exact:true}).waitFor();
    const beforeDownload=await state();
    const downloadPromise=page.waitForEvent("download");
    await page.getByRole("link",{name:"下载我的日历文件",exact:true}).click();
    const download=await downloadPromise;
    const file=path.join(out,"meetmind-action.ics");
    await download.saveAs(file);
    const calendar=fs.readFileSync(file,"utf8"),unfolded=calendar.replace(/\r\n /g,"");
    assert.ok(unfolded.includes("DTSTART:20260915T113000Z\r\n"));
    assert.ok(unfolded.includes("DTEND:20260915T121500Z\r\n"));
    assert.ok(unfolded.includes("SUMMARY:周二一起整理三张旅行照片\r\n"));
    assert.ok(unfolded.includes("LOCATION:楼下咖啡厅\r\n"));
    assert.ok(!/\r\n(?:ATTENDEE|ORGANIZER|METHOD|BEGIN:VALARM)/.test(unfolded));
    assert.deepEqual(await state(),beforeDownload);
    await page.getByLabel("查看身份",{exact:true}).selectOption("bo");
    await page.getByRole("button",{name:"这次不参加",exact:true}).click();
    await page.locator(".decision").filter({hasText:"阿博"}).filter({hasText:"这次不参加"}).waitFor();
    assert.equal(await page.getByRole("link",{name:"下载我的日历文件",exact:true}).count(),0);
    const boCalendar=calendarUrl.replace("viewer=alice","viewer=bo");
    assert.equal((await page.request.get(new URL(boCalendar,page.url()).href)).status(),400);
    await page.getByLabel("查看身份",{exact:true}).selectOption("alice");
    await page.getByLabel("现实结果说明",{exact:true}).fill("我选好了三张，阿博这次没有参加。");
    await page.getByRole("button",{name:"自报已完成",exact:true}).click();
    await page.getByRole("button",{name:"撤回我的结果报告",exact:true}).waitFor();
    const reported=await state();
    assert.deepEqual(Object.keys(reported.entities.find(e=>e.id===action.id).outcomes),["alice"]);
    await page.screenshot({path:path.join(out,"desktop-action.png"),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.getByLabel("呈现模式",{exact:true}).selectOption("2d");
    await page.locator(".baseline").waitFor({state:"visible"});
    const card=page.locator('.baseline-card[data-entity-id="'+action.id+'"]');
    await card.getByText(/楼下咖啡厅/).waitFor();
    await page.screenshot({path:path.join(out,"mobile-action.png"),fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.getByRole("button",{name:"撤回我的结果报告",exact:true}).click();
    await page.getByLabel("现实结果说明",{exact:true}).waitFor();
    await page.locator('#entities [data-entity-id="'+imported.id+'"]').click();
    await page.getByRole("button",{name:"撤回这段经历",exact:true}).click();
    await page.locator('#entities [data-entity-id="'+imported.id+'"]').waitFor({state:"detached"});
    await page.locator('#entities [data-entity-id="'+action.id+'"]').click();
    await page.locator("#detail .warning").waitFor();
    const final=await state(),current=final.entities.find(e=>e.id===action.id);
    assert.equal(current.basis_status,"withdrawn");
    assert.deepEqual(current.basis_event_ids,[]);
    assert.deepEqual(current.outcomes,{});
    assert.deepEqual(errors,[]);
    fs.writeFileSync(path.join(out,"report.json"),JSON.stringify({mode:"synthetic-no-model",errors,actionId:action.id,created,final,passed:["shared check-in import","user-authored action plan","idempotent submit","no auto acceptance","calendar denied until own acceptance","calendar browser download","UTC calendar times","no invitations","download doesn't mutate state","independent decline","own result report","2D plan parity","mobile layout","withdraw result and basis"]},null,2));
    console.log(out);
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
